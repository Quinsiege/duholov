// дымное колечко
function azRing(x, y, r, d) {
  return `<g class="art-float" style="animation-delay:${d}s"><circle cx="${x}" cy="${y}" r="${r}" fill="none" stroke="#57534e" stroke-width="${r * 0.6 + 3}" opacity=".55"/><circle cx="${x}" cy="${y}" r="${r}" fill="none" stroke="#f5f5f4" stroke-width="${r * 0.6}"/></g>`;
}
// перо кецаля: основание (x, y), длина L, поворот rot (0 — вверх)
function azPlume(K, x, y, L, rot, c1 = '#6ee7b7', c2 = '#047857', d = 0) {
  const f = K.f, w = L * 0.17;
  const p = `M0 0C${f(w)} ${f(-L * 0.25)} ${f(w * 1.1)} ${f(-L * 0.75)} 0 ${f(-L)}C${f(-w * 1.1)} ${f(-L * 0.75)} ${f(-w)} ${f(-L * 0.25)} 0 0Z`;
  const g = `<path d="${p}" fill="${K.lin([K.shade(c1, 0.35), c1, c2])}" stroke="${K.shade(c2, -0.5)}" stroke-width="1.6" stroke-linejoin="round"/>` +
    K.line(`M0 -3L0 ${f(-L * 0.9)}`, K.shade(c2, -0.3), 1.2) + K.line(`M0 ${f(-L * 0.4)}l${f(w * 0.6)} ${f(-L * 0.1)}M0 ${f(-L * 0.4)}l${f(-w * 0.6)} ${f(-L * 0.1)}M0 ${f(-L * 0.62)}l${f(w * 0.55)} ${f(-L * 0.1)}M0 ${f(-L * 0.62)}l${f(-w * 0.55)} ${f(-L * 0.1)}`, '#ecfeff', 1, { op: 0.6 });
  return `<g transform="translate(${x} ${y}) rotate(${rot})"><g class="art-sway" style="animation-delay:${d}s;transform-origin:50% 100%">${g}</g></g>`;
}
// пушистая веточка-жабра аксолотля: основание (x, y), направление rot, длина len
function azGill(K, x, y, rot, len, d) {
  const f = K.f, st = `M0 0Q${f(len * 0.5)} -4 ${len} 0`;
  let g = K.line(st, '#be123c', 7) + K.line(st, '#fb7185', 4);
  for (let i = 1; i <= 4; i++) {
    const t = f(i / 4.6 * len);
    g += `<ellipse cx="${t}" cy="-5" rx="2.6" ry="5" transform="rotate(-25 ${t} -5)" fill="#fda4af" stroke="#be123c" stroke-width="1.1"/><ellipse cx="${t}" cy="4.5" rx="2.6" ry="5" transform="rotate(25 ${t} 4.5)" fill="#fda4af" stroke="#be123c" stroke-width="1.1"/>`;
  }
  g += `<circle cx="${len}" cy="0" r="3.6" fill="#fda4af" stroke="#be123c" stroke-width="1.2"/>`;
  return `<g transform="translate(${x} ${y}) rotate(${rot})"><g class="art-sway" style="animation-delay:${d}s">${g}</g></g>`;
}
// бархатец-цемпасучиль
