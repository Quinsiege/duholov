  let p = '';
  for (let k = 0; k < 2; k++) for (let i = 0; i < 10; i++) {
    const a = i * 36 + k * 18, rr = k ? r * 0.55 : r, cx = f(x + rr * 0.55 * Math.cos(a * Math.PI / 180)), cy = f(y + rr * 0.55 * Math.sin(a * Math.PI / 180));
    p += `<ellipse cx="${cx}" cy="${cy}" rx="${f(rr * 0.5)}" ry="${f(rr * 0.2)}" transform="rotate(${a} ${cx} ${cy})" fill="${k ? K.shade(c, 0.35) : c}"/>`;
  }
  return `<g stroke="${K.shade(c, -0.5)}" stroke-width="${f(Math.max(0.5, r * 0.08))}">${p}</g><circle cx="${x}" cy="${y}" r="${f(r * 0.22)}" fill="#fde047" stroke="#a16207" stroke-width=".8"/>`;
