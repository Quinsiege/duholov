    A(G.spec, { cx: (cx - R * .4).toFixed(1), cy: (cy - R * .5).toFixed(1), rx: (R * .36).toFixed(1), ry: (R * .16).toFixed(1), transform: `rotate(-32 ${(cx - R * .4).toFixed(1)} ${(cy - R * .5).toFixed(1)})` });
