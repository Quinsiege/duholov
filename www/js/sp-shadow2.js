// нотка мурлыканья
function sh2Note(x, y, k, c, d) {
  return `<g class="art-float" style="animation-delay:${d}"><g transform="translate(${x} ${y}) scale(${k})"><path d="M3.4 0V-15Q9 -12 10 -6" fill="none" stroke="${c}" stroke-width="2.2" stroke-linecap="round"/><ellipse cx="0" cy="0" rx="4.4" ry="3.2" transform="rotate(-22)" fill="${c}"/></g></g>`;
}

// спираль из полуокружностей: центр, шаг, число полувитков
function sh2Spiral(cx, cy, st, n) {
  let x = cx, d = `M${cx} ${cy}`;
  for (let i = 1; i <= n; i++) {
    x += (i % 2 ? 1 : -1) * i * st;
    d += `A${Math.round(i * st * 5) / 10} ${Math.round(i * st * 5) / 10} 0 0 1 ${Math.round(x * 10) / 10} ${cy}`;
  }
  return d;
}

// обрезка по контуру (для заливок поверх vol)
function sh2Clip(K, d, inner) {
  const i = K.id('c');
  K.def(`<clipPath id="${i}"><path d="${d}"/></clipPath>`);
  return `<g clip-path="url(#${i})">${inner}</g>`;
}
// вертикальный градиент с прозрачностью в координатах холста: [[offset, цвет, прозрачность], …]
function sh2LinA(K, stops, y1, y2) {
  const i = K.id('a');
  K.def(`<linearGradient id="${i}" gradientUnits="userSpaceOnUse" x1="0" y1="${y1}" x2="0" y2="${y2}">${stops.map(([o, c, a]) => `<stop offset="${o}" stop-color="${c}" stop-opacity="${a}"/>`).join('')}</linearGradient>`);
  return `url(#${i})`;
}
