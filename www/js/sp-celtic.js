// трискель — три спирали из общего центра
function ceTriskele(K, x, y, R, c, w) {
  const f = K.f;
  let d = '';
  for (let i = 0; i < 3; i++) {
    const a = (-90 + i * 120) * Math.PI / 180, dd = R * 0.52, cx = x + dd * Math.cos(a), cy = y + dd * Math.sin(a), T = Math.PI * 3.2, p0 = a + Math.PI - T;
    for (let k = 0; k <= 40; k++) { const t = k / 40, ph = p0 + T * t, rr = dd * t; d += `${k ? 'L' : 'M'}${f(cx + rr * Math.cos(ph))} ${f(cy + rr * Math.sin(ph))}`; }
  }
  return K.line(d, c, w);
}
